#!/usr/bin/env node
/**
 * Typed clients (TypeScript + Python) from the OpenAPI 3.1 of the kon SDK
 * ============================================================================
 *
 * Input: `packages/sdk/openapi/kitsuden.openapi.json`, the document that
 * `apps/api/scripts/sdk-openapi.ts` writes from every `defineOperacion` of the
 * installed kons and the core (same function as `GET /api/docs/openapi.json`).
 *
 * Output (never edit by hand; regenerate):
 *
 *   packages/sdk/src/generated/            TypeScript: one file per kon + index
 *   packages/sdk-python/kitsuden/_generated/  Python: one module per kon + index
 *
 * Deterministic on purpose: no dates, no absolute paths, everything sorted, so
 * running it twice gives the same bytes and CI can diff the result.
 *
 *   node scripts/sdk/generate.mjs                 # write
 *   node scripts/sdk/generate.mjs --check         # exit 1 if the committed code is stale
 *   node scripts/sdk/generate.mjs --spec=<file>   # another OpenAPI document
 *   node scripts/sdk/generate.mjs --from-url=<API origin>
 *        # fetch <API>/api/docs/openapi.json, keep the kon SDK operations
 *        # (`x-kitsuden-operation`), write it as the snapshot, then generate:
 *        # for a project whose installed kons are not in this repository.
 *
 * No dependencies: plain Node (>= 18). No third-party generator, so no license
 * to check; the JSON Schema → TypeScript / Python mapping is below.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const RAIZ = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SPEC_POR_DEFECTO = join(RAIZ, "packages/sdk/openapi/kitsuden.openapi.json");
const args = process.argv.slice(2);
const arg = (n) => args.find((a) => a.startsWith(`--${n}=`))?.slice(n.length + 3);

// `--out-ts` / `--out-py`: otra carpeta (las pruebas del generador).
const DIR_TS = resolve(arg("out-ts") ?? join(RAIZ, "packages/sdk/src/generated"));
const DIR_PY = resolve(arg("out-py") ?? join(RAIZ, "packages/sdk-python/kitsuden/_generated"));
const comprobar = args.includes("--check");
const rutaSpec = resolve(arg("spec") ?? SPEC_POR_DEFECTO);
const desdeUrl = arg("from-url");

const CABECERA =
  "Generated by scripts/sdk/generate.mjs from packages/sdk/openapi/kitsuden.openapi.json. Do not edit: run `pnpm sdk:generate`.";

// ═════════════════════════════════════════════════════════════════════════════
// 1. The document
// ═════════════════════════════════════════════════════════════════════════════

async function cargarSpec() {
  if (desdeUrl) {
    const base = desdeUrl.replace(/\/+$/, "").replace(/\/api$/, "");
    const res = await fetch(`${base}/api/docs/openapi.json`, {
      headers: { accept: "application/json" },
    });
    if (!res.ok) throw new Error(`GET ${base}/api/docs/openapi.json → ${res.status}`);
    const vivo = await res.json();
    const paths = {};
    for (const camino of Object.keys(vivo.paths ?? {}).sort()) {
      for (const metodo of ["get", "put", "post", "delete", "patch"]) {
        const o = vivo.paths[camino]?.[metodo];
        if (!o?.["x-kitsuden-operation"]) continue;
        (paths[camino] ??= {})[metodo] = o;
      }
    }
    const kons = new Set(
      Object.values(paths).flatMap((i) =>
        Object.values(i).map((o) => o["x-kitsuden-operation"].kon)
      )
    );
    const doc = {
      openapi: "3.1.0",
      info: { ...vivo.info, title: "Kitsuden API — kon SDK operations" },
      servers: vivo.servers,
      tags: (vivo.tags ?? [])
        .filter((t) => kons.has(t.name))
        .sort((a, b) => a.name.localeCompare(b.name)),
      paths,
      components: {
        schemas: { Problem: vivo.components.schemas.Problem },
        securitySchemes: vivo.components.securitySchemes,
      },
    };
    mkdirSync(dirname(rutaSpec), { recursive: true });
    writeFileSync(rutaSpec, `${JSON.stringify(doc, null, 2)}\n`);
    console.error(`[sdk] snapshot from ${base}: ${rel(rutaSpec)}`);
    return doc;
  }
  if (!existsSync(rutaSpec))
    throw new Error(`${rel(rutaSpec)} does not exist: run pnpm sdk:openapi first`);
  return JSON.parse(readFileSync(rutaSpec, "utf8"));
}

function rel(p) {
  return relative(RAIZ, p).replaceAll("\\", "/");
}

// ═════════════════════════════════════════════════════════════════════════════
// 2. Names
// ═════════════════════════════════════════════════════════════════════════════

const palabras = (s) =>
  String(s)
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w.toLowerCase());
const camel = (s) => {
  const w = palabras(s);
  const r = w.map((x, i) => (i === 0 ? x : x[0].toUpperCase() + x.slice(1))).join("");
  return /^[0-9]/.test(r) ? `_${r}` : r;
};
const pascal = (s) => {
  const r = palabras(s)
    .map((x) => x[0].toUpperCase() + x.slice(1))
    .join("");
  return /^[0-9]/.test(r) ? `_${r}` : r;
};
const snake = (s) => {
  const r = palabras(s).join("_");
  return /^[0-9]/.test(r) ? `_${r}` : r;
};

const PY_KEYWORDS = new Set(
  "False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield".split(
    " "
  )
);
const pyIdent = (s) => {
  const n = snake(s) || "_";
  return PY_KEYWORDS.has(n) ? `${n}_` : n;
};
const esIdentTs = (k) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k);
const esIdentPy = (k) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(k) && !PY_KEYWORDS.has(k);

/** Names the clients use for their own members: a kon cannot take them. */
const RESERVADOS_TS = new Set([
  "request",
  "withOptions",
  "operations",
  "options",
  "baseUrl",
  "constructor",
  "toString",
]);
const RESERVADOS_PY = new Set(["request", "operations", "options", "base_url", "close", "aclose"]);

// ═════════════════════════════════════════════════════════════════════════════
// 3. The model: kons → operations
// ═════════════════════════════════════════════════════════════════════════════

const ORDEN_METODOS = ["get", "put", "post", "delete", "patch"];
const CAMPOS_DE_ITEMS = ["docs", "data", "items", "rows", "results", "entries"];

function tipoDeContenido(tipo) {
  if (!tipo) return "empty";
  // Un flujo (kitsuden2.md C5): Server-Sent Events, un evento JSON por `data:`.
  if (tipo === "text/event-stream") return "event-stream";
  if (tipo === "application/json" || tipo.endsWith("+json")) return "json";
  if (tipo.startsWith("text/") || tipo === "application/javascript") return "text";
  return "binary";
}

function construirModelo(doc) {
  const descripcionDeKon = new Map((doc.tags ?? []).map((t) => [t.name, t.description ?? ""]));
  const kons = new Map();
  for (const camino of Object.keys(doc.paths).sort()) {
    for (const metodo of ORDEN_METODOS) {
      const o = doc.paths[camino][metodo];
      if (!o) continue;
      const x = o["x-kitsuden-operation"];
      if (!x) continue;
      const konId = x.kon;
      if (!kons.has(konId)) {
        const corto = konId.replace(/^kon-/, "");
        kons.set(konId, {
          id: konId,
          corto,
          ts: camel(corto),
          py: pyIdent(corto),
          tipo: pascal(corto),
          descripcion: descripcionDeKon.get(konId) ?? "",
          ops: [],
        });
      }
      const params = o.parameters ?? [];
      const deCamino = params.filter((p) => p.in === "path");
      const deQuery = params.filter((p) => p.in === "query");
      const nombres = new Set();
      for (const p of [...deCamino, ...deQuery]) {
        if (nombres.has(p.name))
          throw new Error(
            `${o.operationId}: parameter '${p.name}' is both in the path and the query`
          );
        if (p.name === "body")
          throw new Error(`${o.operationId}: a parameter cannot be called 'body'`);
        nombres.add(p.name);
      }
      let cuerpo = null;
      if (o.requestBody) {
        const [tipo, media] = Object.entries(o.requestBody.content)[0];
        cuerpo = {
          requerido: !!o.requestBody.required,
          formato: tipo === "multipart/form-data" ? "multipart" : "json",
          esquema: media.schema ?? {},
        };
      }
      const exitos = [];
      for (const estado of Object.keys(o.responses).sort()) {
        const n = Number(estado);
        if (!(n >= 200 && n < 400)) continue;
        const r = o.responses[estado];
        const [tipo, media] = Object.entries(r.content ?? {})[0] ?? [];
        const clase = n >= 300 ? "redirect" : n === 204 ? "empty" : tipoDeContenido(tipo);
        // En un flujo, el esquema que importa es el de CADA evento.
        const esquema =
          clase === "event-stream" ? (media?.["x-kitsuden-event-schema"] ?? null) : (media?.schema ?? null);
        exitos.push({ estado: n, tipo: tipo ?? null, clase, esquema });
      }
      const op = {
        kon: konId,
        id: x.id,
        operationId: o.operationId,
        ts: camel(x.id),
        py: pyIdent(x.id),
        tipo: pascal(x.id),
        metodo: metodo.toUpperCase(),
        camino,
        resumen: o.summary ?? "",
        descripcion: o.description ?? "",
        deCamino,
        deQuery,
        cuerpo,
        exitos,
        errores: [...(x.errors ?? [])],
        idempotente: !!x.idempotent,
        soloLectura: !!x.readOnly,
        sensible: !!x.sensitive,
        scope: x.scope ?? null,
        acceso: x.access ?? null,
        mcp: x.mcp?.tool ?? null,
        flujo: x.stream === true,
        paginacion: null,
      };
      // Un flujo no se pagina: ya es un iterable.
      op.paginacion = op.flujo ? null : paginacionDe(op);
      kons.get(konId).ops.push(op);
    }
  }
  const lista = [...kons.values()].sort((a, b) => a.id.localeCompare(b.id));
  const vistosTs = new Set();
  const vistosPy = new Set();
  for (const k of lista) {
    if (RESERVADOS_TS.has(k.ts) || vistosTs.has(k.ts))
      throw new Error(`kon ${k.id}: TS name '${k.ts}' is taken`);
    if (RESERVADOS_PY.has(k.py) || vistosPy.has(k.py))
      throw new Error(`kon ${k.id}: Python name '${k.py}' is taken`);
    vistosTs.add(k.ts);
    vistosPy.add(k.py);
    k.ops.sort((a, b) => a.id.localeCompare(b.id));
    const ts = new Set();
    const py = new Set();
    for (const op of k.ops) {
      if (ts.has(op.ts)) throw new Error(`${k.id}: two operations named '${op.ts}'`);
      if (py.has(op.py)) throw new Error(`${k.id}: two operations named '${op.py}'`);
      ts.add(op.ts);
      py.add(op.py);
    }
  }
  return lista;
}

/** Page/offset/cursor lists: which query parameter moves and where the items are. */
function paginacionDe(op) {
  const q = op.deQuery.map((p) => p.name);
  const estilo = q.includes("cursor")
    ? "cursor"
    : q.includes("page")
      ? "page"
      : q.includes("offset")
        ? "offset"
        : null;
  if (!estilo || op.metodo !== "GET") return null;
  const exito = op.exitos.find((e) => e.clase === "json");
  const esquema = exito?.esquema;
  let items = null;
  let itemSchema = {};
  if (esquema?.type === "array") {
    items = "";
    itemSchema = esquema.items ?? {};
  } else if (esquema?.properties) {
    const arrays = Object.entries(esquema.properties).filter(([, s]) => s?.type === "array");
    const elegido =
      arrays.find(([k]) => CAMPOS_DE_ITEMS.includes(k)) ??
      (arrays.length === 1 ? arrays[0] : undefined);
    if (elegido) {
      items = elegido[0];
      itemSchema = elegido[1].items ?? {};
    }
  }
  return {
    estilo,
    items,
    itemSchema,
    limite: q.includes("limit") ? "limit" : q.includes("pageSize") ? "pageSize" : null,
  };
}

// ═════════════════════════════════════════════════════════════════════════════
// 4. JSON Schema → TypeScript
// ═════════════════════════════════════════════════════════════════════════════

const jsdoc = (texto, sangria) => {
  const t = String(texto ?? "").trim();
  if (!t) return "";
  const lineas = t.replaceAll("*/", "*\\/").split(/\r?\n/);
  if (lineas.length === 1) return `${sangria}/** ${lineas[0]} */\n`;
  return `${sangria}/**\n${lineas.map((l) => `${sangria} *${l ? ` ${l}` : ""}`).join("\n")}\n${sangria} */\n`;
};

const literalTs = (v) => (v === null ? "null" : JSON.stringify(v));

function unionTs(partes) {
  const unicas = [...new Set(partes)];
  if (unicas.includes("unknown")) return "unknown";
  return unicas.length === 0 ? "never" : unicas.join(" | ");
}

/**
 * `ancho`: query/path parameters travel as text, so a `string` there also
 * takes a number (the URL is the same).
 */
function ts(s, sangria = "", ancho = false) {
  if (s === true || s === undefined || s === null) return "unknown";
  if (s === false) return "never";
  if (typeof s !== "object") return "unknown";
  if (s.$ref) {
    if (s.$ref === "#/components/schemas/Problem") return "Problem";
    return "unknown";
  }
  if ("const" in s) return literalTs(s.const);
  if (Array.isArray(s.enum)) return unionTs(s.enum.map(literalTs));
  if (Array.isArray(s.anyOf) || Array.isArray(s.oneOf)) {
    const ms = (s.anyOf ?? s.oneOf).map((m) => envolver(ts(m, sangria, ancho)));
    return unionTs(ms);
  }
  if (Array.isArray(s.allOf)) {
    const ms = s.allOf.map((m) => envolver(ts(m, sangria, ancho))).filter((m) => m !== "unknown");
    return ms.length ? [...new Set(ms)].join(" & ") : "unknown";
  }
  if (Array.isArray(s.type)) {
    return unionTs(s.type.map((t) => envolver(ts({ ...s, type: t }, sangria, ancho))));
  }
  switch (s.type) {
    case "string":
      return ancho ? "string | number" : "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      if (Array.isArray(s.prefixItems)) {
        const items = s.prefixItems.map((m) => ts(m, sangria));
        return `[${items.join(", ")}]`;
      }
      return `${envolver(ts(s.items ?? {}, sangria))}[]`;
    }
    case "object":
      return objetoTs(s, sangria);
    default:
      if (s.properties || s.additionalProperties) return objetoTs(s, sangria);
      return "unknown";
  }
}

function envolver(t) {
  return /[|&]/.test(t) && !/^\{[\s\S]*\}$/.test(t) && !/^\[[\s\S]*\]$/.test(t) ? `(${t})` : t;
}

function objetoTs(s, sangria) {
  const props = s.properties ?? {};
  const requeridos = new Set(s.required ?? []);
  const claves = Object.keys(props);
  const extra = s.additionalProperties;
  if (claves.length === 0) {
    if (extra === false) return "Record<string, never>";
    const valor = extra && extra !== true ? ts(extra, sangria) : "unknown";
    const llaves =
      s.propertyNames && Array.isArray(s.propertyNames.enum)
        ? unionTs(s.propertyNames.enum.map(literalTs))
        : null;
    return llaves ? `Partial<Record<${llaves}, ${valor}>>` : `Record<string, ${valor}>`;
  }
  const dentro = `${sangria}  `;
  let out = "{\n";
  for (const k of claves) {
    const p = props[k];
    out += jsdoc(p?.description, dentro);
    out += `${dentro}${esIdentTs(k) ? k : JSON.stringify(k)}${requeridos.has(k) ? "" : "?"}: ${ts(p, dentro)};\n`;
  }
  if (extra && extra !== false) out += `${dentro}[key: string]: unknown;\n`;
  return `${out}${sangria}}`;
}

