function existentes(dir) {
  const salida = [];
  if (!existsSync(dir)) return salida;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === "__pycache__") continue;
      salida.push(...existentes(p));
    } else salida.push(p);
  }
  return salida;
}

