const OPCION_PY = "request_options";

function argumentosPy(op, tipos) {
  const args = [];
  const usados = new Set(["self", OPCION_PY, "body"]);
  for (const p of [...op.deCamino, ...op.deQuery]) {
    let n = pyIdent(p.name);
    while (usados.has(n)) n = `${n}_`;
    usados.add(n);
    const tipo = tipos.tipo(
      p.schema ?? { type: "string" },
      `${op.tipo}Param${pascal(p.name)}`,
      true
    );
    const requerido = p.in === "path" || p.required;
    args.push({
      py: n,
      wire: p.name,
      tipo,
      requerido,
      descripcion: p.description ?? p.schema?.description ?? "",
    });
  }
  return args;
}

function firmaPy(op, args, tipoCuerpo) {
  const partes = ["self", "*"];
  const lista = args;
  for (const a of lista.filter((x) => x.requerido)) partes.push(`${a.py}: ${a.tipo}`);
  if (op.cuerpo?.requerido) partes.push(`body: ${tipoCuerpo}`);
  for (const a of lista.filter((x) => !x.requerido))
    partes.push(`${a.py}: Optional[${a.tipo}] = None`);
  if (op.cuerpo && !op.cuerpo.requerido) partes.push(`body: Optional[${tipoCuerpo}] = None`);
  partes.push(`${OPCION_PY}: Optional[RequestOptions] = None`);
  return partes.join(", ");
}

function mapaPy(args) {
  if (!args.length) return "{}";
  return `{${args.map((a) => `${JSON.stringify(a.wire)}: ${a.py}`).join(", ")}}`;
}

function docOpPy(op, args) {
  let t = docDeOperacion(op);
  const conDesc = args.filter((a) => a.descripcion);
  if (conDesc.length)
    t += `\n\nArgs:\n${conDesc.map((a) => `    ${a.py}: ${a.descripcion.replace(/\s+/g, " ")}`).join("\n")}`;
  return t;
}

function infoPy(op) {
  const i = infoDeOperacion(op);
  // El cliente Python lee un flujo como texto (el SSE tal cual).
  const resp = Object.entries(i.responses)
    .map(([k, v]) => `${k}: ${JSON.stringify(v === "event-stream" ? "text" : v)}`)
    .join(", ");
  const tupla = (xs) =>
    xs.length
      ? `(${xs.map((x) => JSON.stringify(x)).join(", ")}${xs.length === 1 ? "," : ""})`
      : "()";
  let out = `OperationInfo(\n`;
  out += `        kon=${JSON.stringify(i.kon)},\n        id=${JSON.stringify(i.id)},\n        operation_id=${JSON.stringify(i.operationId)},\n`;
  out += `        method=${JSON.stringify(i.method)},\n        path=${JSON.stringify(i.path)},\n`;
  out += `        path_params=${tupla(i.pathParams)},\n        query_params=${tupla(i.queryParams)},\n`;
  out += `        body=${i.body ? JSON.stringify(i.body) : "None"},\n        responses={${resp}},\n`;
  out += `        idempotent=${i.idempotent ? "True" : "False"},\n        read_only=${i.readOnly ? "True" : "False"},\n`;
  out += `        sensitive=${i.sensitive ? "True" : "False"},\n        scope=${i.scope ? JSON.stringify(i.scope) : "None"},\n`;
  out += `        mcp_tool=${i.mcpTool ? JSON.stringify(i.mcpTool) : "None"},\n        errors=${tupla(i.errors)},\n`;
  if (i.pagination) {
    out += `        pagination=PaginationInfo(style=${JSON.stringify(i.pagination.style)}, items=${i.pagination.items === null ? "None" : JSON.stringify(i.pagination.items)}, limit=${i.pagination.limit ? JSON.stringify(i.pagination.limit) : "None"}),\n`;
  }
  out += `    )`;
  return out;
}

function respuestaPy(op, tipos) {
  const partes = op.exitos.map((e, i) => {
    if (e.clase === "json")
      return tipos.tipo(e.esquema ?? {}, `${op.tipo}Response${i === 0 ? "" : e.estado}`);
    if (e.clase === "text" || e.clase === "event-stream") return "str";
    if (e.clase === "binary") return "bytes";
    if (e.clase === "redirect") return "RedirectResult";
    return "None";
  });
  return unionPy(partes);
}

function generarPyKon(k) {
  const tipos = new TiposPy();
  const metodos = [];
  for (const op of k.ops) {
    const args = argumentosPy(op, tipos);
    let tipoCuerpo = null;
    if (op.cuerpo) {
      tipoCuerpo =
        op.cuerpo.formato === "multipart"
          ? "Dict[str, Any]"
          : tipos.tipo(op.cuerpo.esquema, `${op.tipo}Body`);
    }
    const respuesta = respuestaPy(op, tipos);
    const item = op.paginacion ? tipos.tipo(op.paginacion.itemSchema, `${op.tipo}Item`) : null;
    metodos.push({ op, args, tipoCuerpo, respuesta, item });
  }
  const alias = [];
  for (const m of metodos) {
    // `X = None` is not a valid type alias for checkers; `Literal[None]` is the same type.
    alias.push(`${m.op.tipo}Result = ${m.respuesta === "None" ? "Literal[None]" : m.respuesta}`);
  }

  let out = `# ${CABECERA}\n# ${k.id}\n# fmt: off\n# flake8: noqa\n`;
  out += `from __future__ import annotations\n\n`;
  out += `from typing import Any, AsyncIterator, Dict, Iterator, List, Literal, Optional, Union\n\n`;
  out += `from typing import TypedDict\n\n`;
  out += `from ..._runtime import (\n    AsyncKonApi,\n    KonApi,\n    OperationInfo,\n    Outcome,\n    PaginationInfo,\n    Problem,\n    RedirectResult,\n    RequestOptions,\n)\n\n`;
  out += `__all__ = ["${k.tipo}Api", "Async${k.tipo}Api", "OPERATIONS"]\n\n\n`;
  out += tipos.emitir();
  out += alias.join("\n") + "\n\n\n";
  out += `OPERATIONS: Dict[str, OperationInfo] = {\n`;
  for (const { op } of metodos) out += `    ${JSON.stringify(op.id)}: ${infoPy(op)},\n`;
  out += `}\n\n\n`;

  for (const asincrono of [false, true]) {
    const clase = asincrono ? `Async${k.tipo}Api` : `${k.tipo}Api`;
    out += `class ${clase}(${asincrono ? "AsyncKonApi" : "KonApi"}):\n`;
    out += docPy(`${k.id}${k.descripcion ? `\n\n${k.descripcion}` : ""}`, "    ");
    out += `\n    kon = ${JSON.stringify(k.id)}\n`;
    for (const m of metodos) {
      const { op, args, tipoCuerpo } = m;
      out += `\n    ${asincrono ? "async " : ""}def ${op.py}(${firmaPy(op, args, tipoCuerpo)}) -> Outcome[${op.tipo}Result]:\n`;
      out += docPy(docOpPy(op, args), "        ");
      out += `        return ${asincrono ? "await " : ""}self._call(OPERATIONS[${JSON.stringify(op.id)}], ${mapaPy(args)}, ${op.cuerpo ? "body" : "None"}, ${OPCION_PY})\n`;
      if (op.paginacion) {
        const mover =
          op.paginacion.estilo === "cursor"
            ? "cursor"
            : op.paginacion.estilo === "page"
              ? "page"
              : "offset";
        const sin = args.filter((a) => a.wire !== mover);
        const firma = firmaPy({ ...op, cuerpo: null }, sin, null);
        const it = asincrono ? "AsyncIterator" : "Iterator";
        out += `\n    def iter_${op.py}(${firma}) -> ${it}[${m.item}]:\n`;
        out += docPy(
          `Every item of \`${op.py}\`, page after page (moves \`${mover}\`).\n\nStops on an empty or short page, or when the response says there is no more. Raises \`ProposalPendingError\` if a page needs human approval.`,
          "        "
        );
        out += `        return self._iterate(OPERATIONS[${JSON.stringify(op.id)}], ${mapaPy(sin)}, ${OPCION_PY})\n`;
      }
    }
    out += `\n\n`;
  }
  return out.replace(/\n{3,}$/, "\n");
}

