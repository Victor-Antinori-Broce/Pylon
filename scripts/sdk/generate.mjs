const literalPy = (v) =>
  v === null
    ? "None"
    : v === true
      ? "True"
      : v === false
        ? "False"
        : typeof v === "string"
          ? JSON.stringify(v)
          : String(v);

function unionPy(partes) {
  const unicas = [...new Set(partes)];
  if (unicas.includes("Any")) return "Any";
  if (unicas.length === 0) return "Any";
  if (unicas.length === 1) return unicas[0];
  const sinNone = unicas.filter((u) => u !== "None");
  if (sinNone.length < unicas.length) {
    return sinNone.length === 1
      ? `Optional[${sinNone[0]}]`
      : `Optional[Union[${sinNone.join(", ")}]]`;
  }
  return `Union[${unicas.join(", ")}]`;
}

/** The TypedDicts of one Python module, deduplicated by shape. */
class TiposPy {
  constructor() {
    this.porFirma = new Map();
    this.nombres = new Set();
    this.defs = [];
  }

  nombreLibre(base) {
    let n = base;
    for (let i = 2; this.nombres.has(n); i++) n = `${base}${i}`;
    this.nombres.add(n);
    return n;
  }

  tipo(s, nombre, ancho = false) {
    if (s === true || s === undefined || s === null) return "Any";
    if (s === false) return "Any";
    if (typeof s !== "object") return "Any";
    if (s.$ref) return s.$ref === "#/components/schemas/Problem" ? "Problem" : "Any";
    if ("const" in s) return `Literal[${literalPy(s.const)}]`;
    if (Array.isArray(s.enum)) {
      const valores = s.enum.filter((v) => v !== null && typeof v !== "object");
      const conNone = s.enum.includes(null);
      if (valores.length === 0) return conNone ? "None" : "Any";
      const lit = `Literal[${valores.map(literalPy).join(", ")}]`;
      return conNone ? `Optional[${lit}]` : lit;
    }
    if (Array.isArray(s.anyOf) || Array.isArray(s.oneOf)) {
      const ms = (s.anyOf ?? s.oneOf).map((m, i) =>
        this.tipo(m, `${nombre}${i === 0 ? "" : `V${i + 1}`}`, ancho)
      );
      return unionPy(ms);
    }
    if (Array.isArray(s.allOf)) {
      const objetos = s.allOf.filter(
        (m) => m && typeof m === "object" && (m.type === "object" || m.properties)
      );
      if (objetos.length === s.allOf.length && objetos.length > 0) {
        const props = {};
        const req = [];
        for (const m of objetos) {
          Object.assign(props, m.properties ?? {});
          req.push(...(m.required ?? []));
        }
        return this.tipo({ type: "object", properties: props, required: req }, nombre, ancho);
      }
      return "Any";
    }
    if (Array.isArray(s.type))
      return unionPy(s.type.map((t) => this.tipo({ ...s, type: t }, nombre, ancho)));
    switch (s.type) {
      case "string":
        return ancho ? "Union[str, int]" : "str";
      case "integer":
        return "int";
      case "number":
        return "float";
      case "boolean":
        return "bool";
      case "null":
        return "None";
      case "array":
        if (Array.isArray(s.prefixItems)) {
          return `List[${unionPy(s.prefixItems.map((m, i) => this.tipo(m, `${nombre}Item${i + 1}`)))}]`;
        }
        return `List[${this.tipo(s.items ?? {}, `${nombre}Item`)}]`;
      case "object":
        return this.objeto(s, nombre);
      default:
        if (s.properties || s.additionalProperties) return this.objeto(s, nombre);
        return "Any";
    }
  }

  objeto(s, nombre) {
    const props = s.properties ?? {};
    const claves = Object.keys(props);
    if (claves.length === 0) {
      const extra = s.additionalProperties;
      return `Dict[str, ${extra && extra !== true ? this.tipo(extra, `${nombre}Value`) : "Any"}]`;
    }
    const requeridos = new Set(s.required ?? []);
    const campos = claves.map((k) => ({
      clave: k,
      requerido: requeridos.has(k),
      tipo: this.tipo(props[k], `${nombre}${pascal(k) || "Field"}`),
      descripcion: props[k]?.description ?? "",
    }));
    const firma = JSON.stringify(campos.map((c) => [c.clave, c.requerido, c.tipo]));
    const previo = this.porFirma.get(firma);
    if (previo) return previo;
    const n = this.nombreLibre(nombre);
    this.porFirma.set(firma, n);
    this.defs.push({ nombre: n, campos, descripcion: s.description ?? "" });
    return n;
  }

  emitir() {
    let out = "";
    for (const d of this.defs) out += typedDictPy(d);
    return out;
  }
}

function docPy(texto, sangria) {
  const t = String(texto ?? "").trim();
  if (!t) return "";
  const limpio = t.replaceAll("\\", "\\\\").replaceAll('"""', '\\"\\"\\"');
  const lineas = limpio.split(/\r?\n/);
  if (lineas.length === 1) return `${sangria}"""${lineas[0]}"""\n`;
  return `${sangria}"""${lineas[0]}\n${lineas
    .slice(1)
    .map((l) => (l ? `${sangria}${l}` : ""))
    .join("\n")}\n${sangria}"""\n`;
}

function typedDictPy({ nombre, campos, descripcion }) {
  const req = campos.filter((c) => c.requerido);
  const opc = campos.filter((c) => !c.requerido);
  const todosIdent = campos.every((c) => esIdentPy(c.clave));
  let out = "";
  if (todosIdent) {
    if (req.length && opc.length) {
      out += `class _${nombre}Required(TypedDict):\n`;
      for (const c of req) out += `    ${c.clave}: ${c.tipo}\n`;
      out += `\n\nclass ${nombre}(_${nombre}Required, total=False):\n`;
      out += docPy(descripcion, "    ");
      for (const c of opc) out += `    ${c.clave}: ${c.tipo}\n`;
    } else {
      out += `class ${nombre}(TypedDict${req.length ? "" : ", total=False"}):\n`;
      out += docPy(descripcion, "    ");
      for (const c of campos) out += `    ${c.clave}: ${c.tipo}\n`;
    }
  } else {
    const total = opc.length === 0;
    out += `${nombre} = TypedDict(\n    ${JSON.stringify(nombre)},\n    {\n`;
    for (const c of campos) out += `        ${JSON.stringify(c.clave)}: ${c.tipo},\n`;
    out += `    },\n    total=${total ? "True" : "False"},\n)\n`;
  }
  return `${out}\n\n`;
}

