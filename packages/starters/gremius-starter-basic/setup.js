#!/usr/bin/env node

/**
 * Gremius Quick Start Setup Script
 * 
 * This script automates:
 * 1. Dependency installation
 * 2. Docker containers startup
 * 3. Database migrations
 * 4. Initial seed data
 * 5. Dev server startup
 */

import { spawn } from 'child_process';
import { existsSync } from 'fs';
import { writeFile } from 'fs/promises';
import path from 'path';

const COLORS = {
  reset: '\x1b[0m',
  bright: '\x1b[1m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  red: '\x1b[31m',
  cyan: '\x1b[36m',
};

function log(message, color = 'reset') {
  console.log(`${COLORS[color]}${message}${COLORS.reset}`);
}

function runCommand(command, args = [], options = {}) {
  return new Promise((resolve, reject) => {
    const proc = spawn(command, args, {
      stdio: 'pipe',
      shell: true,
      ...options,
    });

    let stdout = '';
    let stderr = '';

    proc.stdout?.on('data', (data) => {
      stdout += data.toString();
      if (options.verbose) process.stdout.write(data);
    });

    proc.stderr?.on('data', (data) => {
      stderr += data.toString();
      if (options.verbose) process.stderr.write(data);
    });

    proc.on('close', (code) => {
      if (code === 0) {
        resolve(stdout);
      } else {
        reject(new Error(`Command failed with code ${code}: ${stderr}`));
      }
    });

    proc.on('error', reject);
  });
}

async function wait(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

async function checkDocker() {
  try {
    await runCommand('docker', ['--version']);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  log('\n🚀 Gremius Quick Start Setup\n', 'bright');
  log('═══════════════════════════════════════\n', 'cyan');

  // Check prerequisites
  log('📋 Checking prerequisites...', 'yellow');
  
  const hasDocker = await checkDocker();
  if (!hasDocker) {
    log('❌ Docker is not installed. Please install Docker first:', 'red');
    log('   https://docs.docker.com/get-docker/\n');
    process.exit(1);
  }
  log('   ✓ Docker found\n', 'green');

  // Step 1: Install dependencies
  log('📦 Step 1/5: Installing dependencies...', 'yellow');
  try {
    await runCommand('pnpm', ['install'], { verbose: true });
    log('   ✓ Dependencies installed\n', 'green');
  } catch (error) {
    log(`   ⚠️  pnpm install failed, trying npm...`, 'yellow');
    try {
      await runCommand('npm', ['install'], { verbose: true });
      log('   ✓ Dependencies installed with npm\n', 'green');
    } catch {
      log('   ❌ Failed to install dependencies\n', 'red');
      process.exit(1);
    }
  }

  // Step 2: Start Docker containers
  log('🐳 Step 2/5: Starting Docker containers...', 'yellow');
  try {
    await runCommand('docker', ['compose', 'up', '-d'], { verbose: true });
    log('   ✓ Containers started\n', 'green');
  } catch (error) {
    log(`   ❌ Failed to start Docker: ${error.message}\n`, 'red');
    process.exit(1);
  }

  // Step 3: Wait for services to be ready
  log('⏳ Step 3/5: Waiting for services to be ready...', 'yellow');
  log('   Waiting 10 seconds for PostgreSQL and Valkey to initialize...');
  await wait(10000);
  log('   ✓ Services should be ready\n', 'green');

  // Step 4: Database migrations
  log('🗄️  Step 4/5: Running database migrations...', 'yellow');
  try {
    await runCommand('pnpm', ['db:push'], { verbose: true });
    log('   ✓ Database schema pushed\n', 'green');
  } catch (error) {
    log(`   ⚠️  Migration warning (may be normal): ${error.message}\n`, 'yellow');
  }

  // Step 5: Seed data
  log('🌱 Step 5/5: Seeding initial data...', 'yellow');
  try {
    await runCommand('pnpm', ['db:seed'], { verbose: true });
    log('   ✓ Initial data seeded\n', 'green');
  } catch (error) {
    log(`   ⚠️  Seed warning (may be normal): ${error.message}\n`, 'yellow');
  }

  // Create .env.local if not exists
  const envLocalPath = path.join(process.cwd(), 'apps', 'api', '.env.local');
  if (!existsSync(envLocalPath)) {
    const envContent = `# Local Development Environment
# Generated by Gremius Setup

NODE_ENV=development
PORT=3000

# Database
DATABASE_URL=postgres://gremius:gremius@localhost:5432/gremius

# Auth
BETTER_AUTH_SECRET=${generateSecret()}
BETTER_AUTH_URL=http://localhost:3000

# Storage
S3_ENDPOINT=http://localhost:9000
S3_ACCESS_KEY=minioadmin
S3_SECRET_KEY=minioadmin
S3_BUCKET=gremius

# Cache
VALKEY_URL=redis://localhost:6379
`;
    await writeFile(envLocalPath, envContent);
    log('   ✓ Created .env.local\n', 'green');
  }

  // Success message
  log('═══════════════════════════════════════\n', 'cyan');
  log('✅ Setup complete! Your Gremius app is ready.\n', 'bright');
  
  log('🎉 Default login credentials:', 'green');
  log('   Email: admin@gremius.dev');
  log('   Password: admin123\n');
  
  log('🚀 Start development server:', 'yellow');
  log('   pnpm dev\n');
  
  log('📱 Your apps will be available at:', 'cyan');
  log('   API:    http://localhost:3000');
  log('   Admin:  http://localhost:3001');
  log('   Web:    http://localhost:3002\n');
  
  log('📚 Next steps:', 'yellow');
  log('   1. Open http://localhost:3001 in your browser');
  log('   2. Login with the credentials above');
  log('   3. Create your first dataset or grimoire\n');
  
  log('═══════════════════════════════════════\n', 'cyan');
}

function generateSecret() {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
  let result = '';
  for (let i = 0; i < 32; i++) {
    result += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return result;
}

main().catch(error => {
  log(`\n❌ Setup failed: ${error.message}`, 'red');
  process.exit(1);
});
